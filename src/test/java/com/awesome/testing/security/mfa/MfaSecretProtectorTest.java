package com.awesome.testing.security.mfa;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import org.junit.jupiter.api.Test;

import java.util.HexFormat;

class MfaSecretProtectorTest {

    private final MfaSecretProtector protector =
            new MfaSecretProtector(
                    new VersionedMfaTextEncryptor(
                            "unit-test-only-encryption-password", "8f9c82cf1d4a63b107a82fc60e0c27ab"));

    @Test
    void shouldEncryptWithAuthenticatedRandomizedCiphertextAndDecrypt() {
        String secret = "JBSWY3DPEHPK3PXP";

        String first = protector.protect(secret);
        String second = protector.protect(secret);

        assertThat(first).isNotEqualTo(secret).isNotEqualTo(second);
        assertThat(protector.reveal(first)).isEqualTo(secret);
        assertThat(protector.reveal(second)).isEqualTo(secret);
    }

    @Test
    void readsAnExistingSecretFromTheRetiredEncryptionFactory() {
        // Fixed fixture generated by Encryptors.delux before migration, using this test's password/salt.
        String legacy =
                "6c2b35e0538831eaa7d494bed785562b2ce7e5c8acdf6ab0b57bd4ab5e18e0a7cc0437f3e63af0543a918776c4b4bf8f";
        assertThat(protector.reveal(legacy)).isEqualTo("JBSWY3DPEHPK3PXP");
        assertThat(protector.protect("JBSWY3DPEHPK3PXP")).startsWith("v2:");
    }

    @Test
    void rejectsTamperingWithoutFallingBackToLegacyDecryption() {
        String ciphertext = protector.protect("JBSWY3DPEHPK3PXP");
        byte[] bytes = HexFormat.of().parseHex(ciphertext.substring(3));
        bytes[bytes.length - 1] ^= 1;
        String tampered = "v2:" + HexFormat.of().formatHex(bytes);
        assertThatThrownBy(() -> protector.reveal(tampered)).isInstanceOf(IllegalStateException.class);
    }
}
