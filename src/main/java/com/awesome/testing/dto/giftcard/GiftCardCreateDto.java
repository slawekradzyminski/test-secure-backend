package com.awesome.testing.dto.giftcard;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Gift card to issue. The code is generated by the server.")
public class GiftCardCreateDto {

    @NotNull(message = "Gift card amount is required")
    @DecimalMin(value = "1.00", message = "Gift card amount must be between 1.00 and 1000.00")
    @DecimalMax(value = "1000.00", message = "Gift card amount must be between 1.00 and 1000.00")
    @Digits(integer = 4, fraction = 2, message = "Gift card amount must have at most 2 decimals")
    @Schema(minimum = "1.00", maximum = "1000.00", multipleOf = 0.01, description = "Initial balance", example = "50.00")
    private BigDecimal amount;

    @Schema(types = {"string", "null"}, format = "local-date-time",
            description = "Server-local end of validity; must be in the future. Null means the card never expires")
    private LocalDateTime expiresAt;

    @Size(max = 255, message = "Recipient username cannot exceed 255 characters")
    @Schema(types = {"string", "null"}, description = "Existing user who receives a GIFT_CARD_ISSUED email with the code",
            example = "client")
    private String recipientUsername;

    @Size(max = 255, message = "Note cannot exceed 255 characters")
    @Schema(types = {"string", "null"}, description = "Internal note, visible to administrators only", example = "Apology for a late delivery")
    private String note;
}
