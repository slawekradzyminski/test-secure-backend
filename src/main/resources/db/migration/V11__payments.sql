-- Card payments reported by payment-service and card refunds sent back to it.
--
-- order_payments: one row per payment-service payment that reached a final
-- result for an order (CAPTURED or FAILED); a captured row is what refunds go
-- back to. payment_notifications: one row per handled result notification,
-- idempotent per request_id, with the order status that was answered.
-- payment_refund_outbox: the card part of each booked refund, delivered to
-- payment-service by a retrying job. All rows go with their order.
DO $migration$
BEGIN
    IF to_regclass('orders') IS NULL THEN
        RETURN;
    END IF;

    CREATE TABLE order_payments (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
        payment_id uuid NOT NULL,
        status varchar(16) NOT NULL CHECK (status IN ('CAPTURED', 'FAILED')),
        amount numeric(10,2) NOT NULL CHECK (amount >= 0),
        currency varchar(3) NOT NULL,
        failure_code varchar(64),
        created_at timestamptz NOT NULL,
        CONSTRAINT uk_order_payments_payment UNIQUE (payment_id)
    );
    CREATE INDEX idx_order_payments_order ON order_payments(order_id, status);
    -- At most one captured payment per order.
    CREATE UNIQUE INDEX uk_order_payments_captured ON order_payments(order_id) WHERE status = 'CAPTURED';

    CREATE TABLE payment_notifications (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        request_id uuid NOT NULL,
        order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
        payment_id uuid NOT NULL,
        status varchar(16) NOT NULL CHECK (status IN ('CAPTURED', 'FAILED')),
        order_status varchar(32) NOT NULL,
        created_at timestamptz NOT NULL,
        CONSTRAINT uk_payment_notifications_request UNIQUE (request_id)
    );
    CREATE INDEX idx_payment_notifications_order ON payment_notifications(order_id);

    CREATE TABLE payment_refund_outbox (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        request_id uuid NOT NULL,
        order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
        payment_id uuid NOT NULL,
        amount numeric(10,2) NOT NULL CHECK (amount > 0),
        reason varchar(255),
        status varchar(16) NOT NULL CHECK (status IN ('PENDING', 'SENT', 'SKIPPED', 'FAILED')),
        attempts integer NOT NULL DEFAULT 0,
        next_attempt_at timestamptz,
        last_error varchar(1000),
        refund_id uuid,
        created_at timestamptz NOT NULL,
        updated_at timestamptz NOT NULL,
        CONSTRAINT uk_payment_refund_outbox_request UNIQUE (request_id)
    );
    CREATE INDEX idx_payment_refund_outbox_due ON payment_refund_outbox(status, next_attempt_at);
    CREATE INDEX idx_payment_refund_outbox_order ON payment_refund_outbox(order_id);
END
$migration$;
