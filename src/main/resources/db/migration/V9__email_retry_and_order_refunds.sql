-- Email delivery retries and refunds booked by warehouse-service.
--
-- email_event keeps the wire payload and destination of every tracked email so
-- that a failed or lost send can be retried; request_id deduplicates customer
-- notifications that warehouse-service retries.
--
-- orders.refunded_amount is the sum of order_refunds, one row per refunded
-- return, idempotent per request_id.
DO $migration$
BEGIN
    IF to_regclass('email_event') IS NOT NULL THEN
        ALTER TABLE email_event ADD COLUMN destination varchar(255);
        ALTER TABLE email_event ADD COLUMN payload text;
        ALTER TABLE email_event ADD COLUMN attempts integer NOT NULL DEFAULT 0;
        ALTER TABLE email_event ADD COLUMN next_attempt_at timestamptz;
        ALTER TABLE email_event ADD COLUMN request_id uuid;
        ALTER TABLE email_event ADD CONSTRAINT uk_email_event_request UNIQUE (request_id);
        CREATE INDEX idx_email_event_retry ON email_event(status, next_attempt_at);
    END IF;

    IF to_regclass('orders') IS NOT NULL THEN
        ALTER TABLE orders ADD COLUMN refunded_amount numeric(10,2) NOT NULL DEFAULT 0;
        ALTER TABLE orders ADD CONSTRAINT ck_orders_refunded_amount
            CHECK (refunded_amount >= 0 AND refunded_amount <= total_amount);

        CREATE TABLE order_refunds (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
            request_id uuid NOT NULL,
            amount numeric(10,2) NOT NULL CHECK (amount > 0),
            reference varchar(255) NOT NULL,
            created_at timestamp(6) NOT NULL,
            CONSTRAINT uk_order_refunds_request UNIQUE (request_id)
        );
        CREATE INDEX idx_order_refunds_order ON order_refunds(order_id);
    END IF;
END
$migration$;
