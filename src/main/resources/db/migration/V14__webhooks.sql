-- User webhook subscriptions, their delivery log and the built-in request inboxes.
--
-- webhook_subscriptions.events is a comma-separated list of event wire names
-- (order.created, ...). The signing secret is stored encrypted with the MFA text
-- encryptor and is only returned when it is created or rotated.
--
-- webhook_deliveries keeps the exact signed body of every attempt so failed
-- deliveries can be retried by WebhookRetryJob and redelivered on request.
-- A PENDING row is due when next_attempt_at has passed; senders claim it by
-- moving next_attempt_at forward, so one delivery is never sent twice at once.
--
-- webhook_inboxes / webhook_inbox_requests let students receive webhooks without
-- an external server (target URL inbox://<token>); only the last 50 requests of
-- an inbox are kept.
CREATE TABLE IF NOT EXISTS webhook_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL,
    url varchar(2048) NOT NULL,
    description varchar(255),
    events varchar(1000) NOT NULL,
    secret varchar(512) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    consecutive_failures integer NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    disabled_reason varchar(500),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_webhook_subscriptions_username ON webhook_subscriptions(username);

CREATE TABLE IF NOT EXISTS webhook_deliveries (
    id uuid PRIMARY KEY,
    subscription_id bigint NOT NULL REFERENCES webhook_subscriptions(id) ON DELETE CASCADE,
    event_id uuid NOT NULL,
    event_type varchar(64) NOT NULL,
    payload text NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('PENDING', 'DELIVERED', 'FAILED')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamptz,
    last_status_code integer,
    last_error varchar(1000),
    response_snippet varchar(500),
    duration_ms bigint,
    created_at timestamptz NOT NULL,
    delivered_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_webhook_deliveries_subscription
    ON webhook_deliveries(subscription_id, created_at);
CREATE INDEX IF NOT EXISTS idx_webhook_deliveries_due ON webhook_deliveries(status, next_attempt_at);

CREATE TABLE IF NOT EXISTS webhook_inboxes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token varchar(64) NOT NULL,
    username varchar(255) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_webhook_inboxes_token UNIQUE (token)
);
CREATE INDEX IF NOT EXISTS idx_webhook_inboxes_username ON webhook_inboxes(username);

CREATE TABLE IF NOT EXISTS webhook_inbox_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_id bigint NOT NULL REFERENCES webhook_inboxes(id) ON DELETE CASCADE,
    received_at timestamptz NOT NULL,
    headers text NOT NULL,
    body text NOT NULL CHECK (length(body) <= 16384)
);
CREATE INDEX IF NOT EXISTS idx_webhook_inbox_requests_inbox ON webhook_inbox_requests(inbox_id, received_at);
