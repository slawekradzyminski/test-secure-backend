-- Loyalty points and gift cards.
--
-- gift_cards holds bearer cards issued by administrators; balance only moves
-- through gift_card_transactions (ISSUED, REDEEMED, RESTORED, DISABLED), one
-- ledger row per change. loyalty_accounts holds one points balance per user,
-- changed only through loyalty_transactions (EARNED, REDEEMED, RESTORED,
-- REVOKED). A ledger reference (order or refund request) makes earning,
-- redemption and restores idempotent.
--
-- cart_tenders is the gift card and points selection of a cart, applied like
-- cart_coupons. The order columns record what checkout took from each tender;
-- they stay NULL for orders paid without one, so their bodies are unchanged.
DO $migration$
BEGIN
    CREATE TABLE gift_cards (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code varchar(19) NOT NULL,
        initial_amount numeric(10,2) NOT NULL,
        balance numeric(10,2) NOT NULL,
        expires_at timestamp(6),
        disabled_at timestamp(6),
        recipient_username varchar(255),
        note varchar(255),
        created_by varchar(255) NOT NULL,
        created_at timestamp(6) NOT NULL,
        updated_at timestamp(6) NOT NULL,
        CONSTRAINT uk_gift_cards_code UNIQUE (code),
        CONSTRAINT ck_gift_cards_code CHECK (code ~ '^GC-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}$'),
        CONSTRAINT ck_gift_cards_amounts CHECK (
            initial_amount >= 1 AND initial_amount <= 1000 AND balance >= 0 AND balance <= initial_amount)
    );

    CREATE TABLE gift_card_transactions (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        gift_card_id bigint NOT NULL REFERENCES gift_cards(id) ON DELETE CASCADE,
        type varchar(16) NOT NULL,
        amount numeric(10,2) NOT NULL,
        balance_after numeric(10,2) NOT NULL,
        order_id bigint,
        reference varchar(80),
        actor varchar(255),
        created_at timestamp(6) NOT NULL,
        CONSTRAINT ck_gift_card_transactions_type CHECK (type IN ('ISSUED', 'REDEEMED', 'RESTORED', 'DISABLED')),
        CONSTRAINT ck_gift_card_transactions_balance CHECK (balance_after >= 0),
        CONSTRAINT uk_gift_card_transactions_reference UNIQUE (gift_card_id, type, reference)
    );
    CREATE INDEX idx_gift_card_transactions_card ON gift_card_transactions(gift_card_id, id);
    CREATE INDEX idx_gift_card_transactions_order ON gift_card_transactions(order_id);

    CREATE TABLE loyalty_accounts (
        username varchar(255) PRIMARY KEY,
        balance bigint NOT NULL,
        lifetime_earned bigint NOT NULL,
        created_at timestamp(6) NOT NULL,
        updated_at timestamp(6) NOT NULL,
        CONSTRAINT ck_loyalty_accounts_points CHECK (balance >= 0 AND lifetime_earned >= 0)
    );

    CREATE TABLE loyalty_transactions (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username varchar(255) NOT NULL REFERENCES loyalty_accounts(username) ON DELETE CASCADE,
        type varchar(16) NOT NULL,
        points bigint NOT NULL,
        balance_after bigint NOT NULL,
        order_id bigint,
        reference varchar(80),
        created_at timestamp(6) NOT NULL,
        CONSTRAINT ck_loyalty_transactions_type CHECK (type IN ('EARNED', 'REDEEMED', 'RESTORED', 'REVOKED')),
        CONSTRAINT ck_loyalty_transactions_points CHECK (points <> 0 AND balance_after >= 0),
        CONSTRAINT uk_loyalty_transactions_reference UNIQUE (username, type, reference)
    );
    CREATE INDEX idx_loyalty_transactions_user ON loyalty_transactions(username, id);
    CREATE INDEX idx_loyalty_transactions_order ON loyalty_transactions(order_id);

    CREATE TABLE cart_tenders (
        username varchar(255) PRIMARY KEY,
        gift_card_code varchar(19),
        points bigint,
        updated_at timestamp(6) NOT NULL,
        CONSTRAINT ck_cart_tenders_points CHECK (points IS NULL OR (points >= 100 AND points % 100 = 0))
    );

    IF to_regclass('orders') IS NULL THEN
        RETURN;
    END IF;

