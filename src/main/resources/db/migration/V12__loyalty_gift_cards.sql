    ALTER TABLE orders ADD COLUMN gift_card_amount numeric(10,2);
    ALTER TABLE orders ADD COLUMN points_redeemed bigint;
    ALTER TABLE orders ADD COLUMN points_amount numeric(10,2);
    ALTER TABLE orders ADD CONSTRAINT ck_orders_gift_card CHECK (
        (gift_card_code IS NULL AND gift_card_amount IS NULL)
        OR (gift_card_code IS NOT NULL AND gift_card_amount > 0));
    ALTER TABLE orders ADD CONSTRAINT ck_orders_points CHECK (
        (points_redeemed IS NULL AND points_amount IS NULL)
        OR (points_redeemed > 0 AND points_amount = points_redeemed / 100.0));
    ALTER TABLE orders ADD CONSTRAINT ck_orders_tenders CHECK (
        COALESCE(gift_card_amount, 0) + COALESCE(points_amount, 0) <= total_amount);

