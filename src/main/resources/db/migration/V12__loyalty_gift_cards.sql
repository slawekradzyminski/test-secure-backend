        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL;
    ALTER TABLE loyalty_transactions ADD CONSTRAINT fk_loyalty_transactions_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL;
END
